import { jsPDF } from 'jspdf';
import { FileDown } from 'lucide-react';
import { Button } from './ui';

export interface ResultRow {
  label: string;
  value: string;
  sub?: string;
}

interface DownloadResultsPdfProps {
  /** Report title, e.g. "Rebar Weight & Cost — Estimate" */
  title: string;
  /** File name for the download, e.g. "rebar-estimate.pdf" */
  fileName: string;
  inputs: ResultRow[];
  results: ResultRow[];
  notes?: string[];
}

/**
 * Shared "Download PDF" button for calculator result cards.
 * Generates a branded CivilMath estimate report client-side with jsPDF.
 */
export default function DownloadResultsPdf({
  title,
  fileName,
  inputs,
  results,
  notes = [],
}: DownloadResultsPdfProps) {
  const handleDownload = () => {
    const doc = new jsPDF({ unit: 'mm', format: 'a4' });
    const W = 210;
    const today = new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    });

    // Header band
    doc.setFillColor(15, 23, 42);
    doc.rect(0, 0, W, 28, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(15);
    doc.text('CIVILMATH', 14, 12);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text('civilmath.com — free construction calculators', 14, 19);
    doc.setFontSize(8);
    doc.text(today, W - 14, 19, { align: 'right' });

    let y = 40;

    const section = (heading: string, rows: ResultRow[]) => {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.setTextColor(10, 132, 255);
      doc.text(heading.toUpperCase(), 14, y);
      y += 3;
      doc.setDrawColor(10, 132, 255);
      doc.setLineWidth(0.6);
      doc.line(14, y, W - 14, y);
      y += 7;
      rows.forEach((r) => {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(10);
        doc.setTextColor(110, 110, 110);
        doc.text(r.label, 14, y);
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(11);
        doc.setTextColor(15, 23, 42);
        doc.text(r.value, W - 14, y, { align: 'right' });
        if (r.sub) {
          y += 5;
          doc.setFont('helvetica', 'normal');
          doc.setFontSize(8);
          doc.setTextColor(150, 150, 150);
          doc.text(r.sub, 14, y);
        }
        y += 8;
        if (y > 268) {
          doc.addPage();
          y = 20;
        }
      });
      y += 4;
    };

    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text(title, 14, y);
    y += 10;

    section('Inputs', inputs);
    section('Results', results);

    if (notes.length > 0) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(15, 23, 42);
      doc.text('NOTES', 14, y);
      y += 7;
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(110, 110, 110);
      notes.forEach((n) => {
        const lines = doc.splitTextToSize('\u2022 ' + n, W - 28);
        doc.text(lines, 14, y);
        y += lines.length * 5 + 1;
        if (y > 272) {
          doc.addPage();
          y = 20;
        }
      });
    }

    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text(
      'Estimate only, not a quote. Verify with your supplier and a qualified engineer.',
      14,
      290
    );
    doc.text('Generated by civilmath.com', W - 14, 290, { align: 'right' });

    doc.save(fileName);
  };

  return (
    <Button
      variant="outline"
      size="sm"
      icon={FileDown}
      onClick={handleDownload}
      aria-label="Download results as PDF"
    >
      PDF
    </Button>
  );
}
