/**
 * Transforms an ArticleData into a full unified Article object.
 */
export function convertArticleDataToArticle(data: ArticleData, entry: BuiltinArticleEntry): Article {
  return {
    slug: data.slug || entry.slug,
    title: entry.title,
    h1: data.h1,
    excerpt: entry.excerpt || data.metaDescription,
    category: entry.category,
    author: 'CivilMath Engineering Editorial Team',
    publishedAt: '2025-01-15T00:00:00.000Z',
    updatedAt: '2026-03-01T00:00:00.000Z',
    readTimeMinutes: entry.readTimeMinutes,
    status: 'published',
    tags: [entry.category, data.primaryKeyword, ...(data.secondaryKeywords?.slice(0, 3) || [])],
    introduction: data.introduction,
    theory: data.theory,
    realWorldApplications: data.realWorldApplications,
    formulas: data.formulas?.map(f => ({
      name: f.name,
      equation: f.equation,
      variables: f.variables,
      reference: f.reference,
    })),
    stepByStepExample: data.stepByStepExample,
    commonErrors: data.commonErrors,
    bestPractices: data.bestPractices,
    designCodes: data.designCodes,
    faqs: data.faqs,
    relatedCalculators: data.relatedCalculators,
    references: data.references,
    seo: {
      seoTitle: data.seoTitle || `${entry.title} | CivilMath`,
      metaDescription: data.metaDescription || entry.excerpt,
      primaryKeyword: data.primaryKeyword || entry.primaryKeyword,
      secondaryKeywords: data.secondaryKeywords || [],
      lsiKeywords: data.lsiKeywords || [],
      canonicalUrl: `https://civilmath.com/articles/${entry.slug}`,
      noindex: false,
    },
    isBuiltin: true,
  };
}
